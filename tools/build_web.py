# Merges content/ into one bundle and builds the web pages.
#   web/widgets.html    preview page (content embedded), published as the Widget Bench artifact
#   web/www/index.html  the same page as a full document for the iPhone app, with local fonts
#   web/www/content.json the merged content, read by the app's native screens
# Run: python3 tools/build_web.py
import glob, json, os, re
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
C = os.path.join(ROOT, "content")

topics = json.load(open(os.path.join(C, "topics.json")))
data = {"topics": topics["topics"], "widgets": topics["widgets"], "cards": [], "problems": [], "terms": [], "quiz": []}
for unit in sorted(glob.glob(os.path.join(C, "*", ""))):
    for name, key in (("flashcards", "cards"), ("practice", "problems"), ("glossary", "terms"), ("quiz", "questions")):
        f = os.path.join(unit, name + ".json")
        if os.path.exists(f):
            data["quiz" if key == "questions" else key] += json.load(open(f))[key]

known = {t["id"] for t in data["topics"]}
for key in ("cards", "problems", "terms", "quiz"):
    for x in data[key]:
        assert x["topics"] and set(x["topics"]) <= known, (key, x.get("id"), x["topics"])

# Plain-text titles for native lists, which do not run MathJax.
SUB = dict(zip("0123456789aeoxhklmnpstijruv+-", "₀₁₂₃₄₅₆₇₈₉ₐₑₒₓₕₖₗₘₙₚₛₜᵢⱼᵣᵤᵥ₊₋"))
def plain(t):
    def math(m):
        s = re.sub(r"\\mathrm\{([^}]*)\}", r"\1", m.group(1))
        s = re.sub(r"_\{([^}]*)\}|_(\w)", lambda g: "".join(SUB.get(ch, ch) for ch in (g.group(1) or g.group(2))), s)
        return re.sub(r"\\(\w+)", lambda g: {"lambda": "λ", "Gamma": "Γ", "Omega": "Ω", "pi": "π"}.get(g.group(1), g.group(1)), s).replace("{", "").replace("}", "")
    return re.sub(r"\$([^$]*)\$", math, t)
for p in data["problems"]:
    p["titleText"] = plain(p["title"])
for t in data["topics"]:
    t["counts"] = {k: sum(t["id"] in x["topics"] for x in data[k]) for k in ("cards", "problems", "terms", "quiz")}

blob = json.dumps(data, ensure_ascii=False)
page = os.path.join(ROOT, "web", "widgets.html")
s = open(page).read()
tag = '<script id="content" type="application/json">'
s = re.sub(re.escape(tag) + r".*?</script>", lambda m: tag + blob.replace("</", "<\\/") + "</script>", s, count=1, flags=re.S)
open(page, "w").write(s)

www = os.path.join(ROOT, "web", "www")
os.makedirs(www, exist_ok=True)
app = re.sub(r'<link rel="preconnect"[^>]*>\s*<link rel="stylesheet" href="https://fonts.googleapis.com[^>]*>',
             '<link rel="stylesheet" href="vendor/fonts.css">', s, count=1)
assert "fonts.googleapis" not in app
head = ('<!doctype html>\n<html lang="en">\n<head>\n<meta charset="utf-8">\n'
        '<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">\n'
        '<!-- Generated by tools/build_web.py from web/widgets.html. Do not edit. -->\n')
app = re.sub(r'<meta name="claude:[^>]*>\n?', "", app)
i = app.index("</style>") + len("</style>")
open(os.path.join(www, "index.html"), "w").write(head + app[:i] + "\n</head>\n<body>\n" + app[i:] + "\n</body>\n</html>\n")
json.dump(data, open(os.path.join(www, "content.json"), "w"), ensure_ascii=False, indent=1)
print("built", {k: len(data[k]) for k in ("cards", "problems", "terms", "quiz")})
