# Copies MathJax and the page fonts into web/www/vendor so the app works offline.
# Needs npm. Run: python3 tools/vendor_web.py
import os, re, shutil, subprocess, tempfile
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
OUT = os.path.join(ROOT, "web", "www", "vendor")
PKGS = ["mathjax@3.2.2", "@fontsource/archivo@5.3.0", "@fontsource/source-sans-3@5.2.8", "@fontsource/ibm-plex-mono@5.2.7"]
FONTS = {"archivo": [500, 700, 800], "source-sans-3": [400, 600], "ibm-plex-mono": [400, 500]}
SUBSETS = ("latin", "latin-ext", "greek")

tmp = tempfile.mkdtemp()
subprocess.run(["npm", "install", "--silent", "--prefix", tmp, *PKGS], check=True)
nm = os.path.join(tmp, "node_modules")
shutil.rmtree(OUT, ignore_errors=True)
os.makedirs(os.path.join(OUT, "mathjax"))
os.makedirs(os.path.join(OUT, "fonts"))
shutil.copy(os.path.join(nm, "mathjax", "es5", "tex-svg-full.js"), os.path.join(OUT, "mathjax"))
shutil.copy(os.path.join(nm, "mathjax", "LICENSE"), os.path.join(OUT, "mathjax", "LICENSE"))

css = []
for fam, weights in FONTS.items():
    pkg = os.path.join(nm, "@fontsource", fam)
    shutil.copy(os.path.join(pkg, "LICENSE"), os.path.join(OUT, "fonts", f"{fam}-LICENSE"))
    for w in weights:
        for block in re.findall(r"/\* (\S+) \*/\s*(@font-face\s*\{.*?\})", open(os.path.join(pkg, f"{w}.css")).read(), re.S):
            name, rule = block
            if not any(name == f"{fam}-{s}-{w}-normal" for s in SUBSETS):
                continue
            rule = re.sub(r"src:[^;]*;", f"src: url(fonts/{name}.woff2) format('woff2');", rule)
            shutil.copy(os.path.join(pkg, "files", f"{name}.woff2"), os.path.join(OUT, "fonts"))
            css.append(rule)
open(os.path.join(OUT, "fonts.css"), "w").write("/* Generated by tools/vendor_web.py from @fontsource (SIL OFL 1.1). */\n" + "\n".join(css) + "\n")
shutil.rmtree(tmp)
print("vendored", len(css), "font faces")
